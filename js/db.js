// Helper to reload data with user custom words
window.reloadWordsDB = function() {
    const activeUser = localStorage.getItem("longlong_active_user") || "default";
    const customWordsJSON = localStorage.getItem("longlong_custom_words_" + activeUser);
    if (customWordsJSON) {
        try {
            const customWords = JSON.parse(customWordsJSON);
            // Deduplicate: remove any core/default word that has the same Hanzi as custom word
            const customHanzis = new Set(customWords.map(w => w.hanzi));
            
            const baseWords = window.WORDS_DB.filter(w => !customHanzis.has(w.hanzi));
            window.WORDS_DB = [...baseWords, ...customWords];
        } catch(e) {
            console.error("Error merging custom words:", e);
        }
    }
};

// Execute merge on load
window.reloadWordsDB();
